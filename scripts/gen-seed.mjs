// Picks the farm the app opens with, before every dev, build and test run.
//
// With private/ present (never committed — see private/README.md), bundles
// private/seed/* into src/seed/seed-data.json and points src/seed/farm.ts and
// src/seed/farm-settings.ts at the private importer and figures. Without it,
// points them at the made-up sample farm in src/seed/sample.ts.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const seedDir = resolve(root, "private/seed");
const outFile = resolve(root, "src/seed/seed-data.json");
const farmFile = resolve(root, "src/seed/farm.ts");
const farmSettingsFile = resolve(root, "src/seed/farm-settings.ts");
const header = "// Generated by scripts/gen-seed.mjs — do not edit, do not commit.\n";

mkdirSync(dirname(outFile), { recursive: true });
if (!existsSync(resolve(root, "private/farm.ts"))) {
  writeFileSync(farmFile, header + 'export * from "./sample";\n');
  writeFileSync(
    farmSettingsFile,
    header + "export const SETTING_OVERRIDES: Record<string, { value: string; source: string; label?: string }> = {};\n",
  );
  console.log("seed: sample farm (no private/ folder)");
  process.exit(0);
}
writeFileSync(farmFile, header + 'export * from "../../private/farm";\n');
writeFileSync(farmSettingsFile, header + 'export { SETTING_OVERRIDES } from "../../private/settings";\n');

const json = (name) => JSON.parse(readFileSync(resolve(seedDir, name), "utf8"));

// Minimal RFC 4180 parser — the CSV has quoted fields with commas in them.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else field += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((f) => f !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((r, i) => {
    const o = { row: i + 2 }; // 1-based line number in the CSV, header is line 1
    header.forEach((h, j) => { o[h] = r[j] ?? ""; });
    return o;
  });
}

const costs = parseCsv(readFileSync(resolve(seedDir, "costs.csv"), "utf8")).map((c) => ({
  row: c.row,
  month: c.month,
  item: c.item,
  amount_kwacha: Number(c.amount_kwacha),
  category: c.category,
  confidence: c.confidence,
  status: c.status,
}));

const seed = {
  generated_from: "private/seed",
  costs,
  sales: json("sales.json"),
  litters: json("litters.json"),
  breeding_stock: json("breeding_stock.json"),
  weights: json("weights.json"),
  stock_history: json("stock_history.json"),
  feed_products: json("feed_products.json"),
};

writeFileSync(outFile, JSON.stringify(seed, null, 2));

const total = costs.reduce((s, c) => s + c.amount_kwacha, 0);
console.log(`seed: private farm — ${costs.length} cost lines totalling K${total.toLocaleString("en-US")}, ${seed.sales.length} sales, ${seed.litters.length} litters`);
